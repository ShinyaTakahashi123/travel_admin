async function main() {
  const commit = process.argv.includes("--commit");
  console.log(commit ? "登録モードで実行します" : "確認モードで実行します（DBには書き込みません）");

  const targets = await prisma.itinerary.findMany({
    where: { id: { in: Object.keys(NEW_DESCRIPTIONS) } },
    select: { id: true, title: true, description: true },
  });
  if (targets.length !== Object.keys(NEW_DESCRIPTIONS).length) {
    const found = new Set(targets.map((t) => t.id));
    const missing = Object.keys(NEW_DESCRIPTIONS).filter((id) => !found.has(id));
    throw new Error(`しおりが見つかりません: ${missing.join(", ")}`);
  }

  for (const it of targets) {
    const next = NEW_DESCRIPTIONS[it.id];
    console.log(`\n■ ${it.title}`);
    console.log(`  旧: ${it.description}`);
    console.log(`  新: ${next}（${next.length}字）`);
  }

  if (!commit) {
    console.log("\n確認モードのため、ここで終了します。問題なければ --commit を付けて実行してください。");
    return;
  }

  for (const [id, description] of Object.entries(NEW_DESCRIPTIONS)) {
    await prisma.itinerary.update({ where: { id }, data: { description } });
  }
  console.log(`\n更新しました: ${Object.keys(NEW_DESCRIPTIONS).length}件`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
