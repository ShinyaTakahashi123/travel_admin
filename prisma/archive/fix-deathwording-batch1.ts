/**
 * 法務(23:34)からの依頼。公開中のしおり全体を「自決・自害・自刃・命を絶・
 * 切腹・身を投げ・入水・投身・心中・殉死・割腹・自ら命」で検索した結果、
 * 制作(このセッション)の担当分として5本が見つかった。歴史上の人物・伝説
 * でも亡くなり方(自害・入水など)は書かない決まりのため、「亡くなった」
 * 「最期を迎えた」までに直す。あわせて、亡くなった人数・年齢・評価の言葉
 * (悲劇など)も外す。
 * 参照: docs/legal/20260930-death-wording-scan.md
 *
 * #40 1d70017a 鳥羽(九鬼嘉隆): 「自刃したと伝えられ」→「最期を迎えたと
 *   伝えられ」
 * #67 2fd67b8b 露天神社(お初天神): 事件の経緯(お初が命を落とす〜)を外し、
 *   近松門左衛門「曾根崎心中」の舞台・「お初天神」の通称の由来だけを残す
 *   (法務の指示どおり、作品名は書いてよい)
 * #127 c97e2205 猿沢池(采女神社): 「入水したと伝わる」を外す
 * #181 6ac70480 猿沢池(采女神社): 「身を投げたという『大和物語』の伝説」
 *   を「采女(うねめ)の伝説」に
 * #228 ea3cdd43 飯盛山(白虎隊): 「自らの命を絶った」→「亡くなった」、
 *   人数(19名)・年齢(16〜17歳)・評価の言葉(悲劇)・唯一助かった隊士の証言
 *   (亡くなり方の詳細に紐づく記述)を外す
 */
import { prisma } from "../src/lib/prisma";
import { findSpotInItinerary, updateSpotInItinerary } from "./lib/spot-lookup";

const COMMIT = process.argv.includes("--commit");

async function fixOne(idPrefix: string, spotName: string, from: string, to: string, label: string) {
  const rows: any[] = await prisma.$queryRawUnsafe(`select id::text from itinerary where id::text like '${idPrefix}%'`);
  const itinId = rows[0]?.id;
  if (!itinId) throw new Error(`しおりが見つかりません(${label})`);
  const spot = await findSpotInItinerary(itinId, { spotName });
  if (!spot.memo!.includes(from)) throw new Error(`一致しません(${label})`);
  console.log(`確認OK: ${label}`);
  if (!COMMIT) return;
  await updateSpotInItinerary(itinId, { spotId: spot.id }, { memo: spot.memo!.replace(from, to) });
  console.log(`COMMITTED: ${label}`);
}

