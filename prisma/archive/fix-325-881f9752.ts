import { prisma } from "../src/lib/prisma";
import { setDaySpotOrder } from "./lib/spot-order";

const ITIN_ID = "881f9752-bf82-464c-b6b7-0ff8e038f904";

async function main() {
  const day1 = await prisma.day.findFirstOrThrow({ where: { itineraryId: ITIN_ID, dayNumber: 1 } });

  const already = await prisma.spot.findFirst({ where: { dayId: day1.id, name: "宿根木集落" } });
  if (already) {
    console.log("already applied, skipping");
    return;
  }

  const tarai = await prisma.spot.findFirstOrThrow({ where: { dayId: day1.id, name: "たらい舟（小木港）" } });
  const toki = await prisma.spot.findFirstOrThrow({ where: { dayId: day1.id, name: "トキの森公園" } });

  const taraiMemo =
    "小木港のたらい舟は、佐渡島南部の小木半島に伝わる、伝統的な小舟です。洗濯桶を改良してつくられたのが始まりと伝えられています。享和2年(1802)の小木地震によって、この一帯の海岸が1メートル以上も隆起し、入り組んだ岩礁地帯が生まれたことで、大きな舟では入り込めない磯へも小回りよく進める、この独特な舟が考え出されたのだそうです。もともとはアワビやサザエ、海藻を採る「磯ねぎ漁」の道具として使われてきましたが、今では女性の船頭が巧みに操る観光名物として、多くの人に親しまれています。円形の舟ならではの揺れを感じながら、小木の入り江の透き通った海を眺めてみましょう。続いては、車でおよそ10分の宿根木集落へ向かいましょう。";

  const tokiMemo =
    "西三川ゴールドパークからは車でおよそ50分です。トキの森公園は、国の特別天然記念物に指定されているトキの生態や、保護の歴史を紹介する施設です。隣接する佐渡トキ保護センターと連携しながら、人とトキが共生する新しい関係づくりに取り組んでいます。トキふれあいプラザでは、大きなガラス越しに、優雅に羽を広げるトキの姿を間近で観察することができます。日本生まれのトキは、平成15年(2003)に最後の1羽が死んで一度絶えてしまいましたが、中国から贈られたトキをもとに繁殖と放鳥が進められ、今では佐渡の空を舞う姿が見られるまでになりました。朱鷺色と呼ばれる、淡いピンク色の羽の美しさを、じっくりと眺めてみましょう。続いては、車でおよそ34分の佐渡歴史伝説館へ向かいましょう。";

  await setDaySpotOrder(day1.id, [
    { id: tarai.id, data: { memo: taraiMemo } },
    {
      create: {
        name: "宿根木集落",
        address: "佐渡市宿根木",
        lat: 37.8091059,
        lng: 138.2438636,
        visitTime: new Date(Date.UTC(1970, 0, 1, 10, 20)),
        stayDurationMin: 50,
        transitMode: "car",
        transitDurationMin: 10,
        memo:
          "たらい舟からは車でおよそ10分です。小木港からほど近い集落ですが、入り組んだ海沿いの道を通るため、車でこのくらいかかります。宿根木は、中世から港として栄え、江戸後期から明治初期にかけては、北前船に関わる船大工や廻船業で発展した集落です。小さな入り江に面して、船板などを利用した板壁の民家がおよそ100棟も密集し、「石置木羽葺屋根」と呼ばれる宿根木独自の屋根を持つ家々が、細い路地の両側に立ち並びます。集落のシンボルとされる「三角家」は、狭い路地の形に合わせて建てられた、舟の形をした独特の建物です。石畳の小径を歩きながら、船大工の町ならではの歴史ある町並みを眺めてみましょう。続いては、車でおよそ20分の佐渡西三川ゴールドパークへ向かいましょう。",
      },
    },
    {
      create: {
        name: "佐渡西三川ゴールドパーク",
        address: "佐渡市西三川835-1",
        lat: 37.8981166,
        lng: 138.2963258,
        visitTime: new Date(Date.UTC(1970, 0, 1, 11, 30)),
        stayDurationMin: 75,
        transitMode: "car",
        transitDurationMin: 20,
        memo:
          "宿根木からは車でおよそ20分です。到着したら、まずこのあたりで昼食をとりましょう。佐渡西三川ゴールドパークは、佐渡最古と伝わる西三川砂金山の跡地にある、体験型の資料館です。平安時代の説話集『今昔物語集』にもその名が記されるほど、古くから知られてきた砂金の産地です。館内では、砂金の歴史を紹介する展示を見学できるほか、指導員のレクチャーを受けながら、実際に砂金採りを体験することができます。見つけた砂金は、その場でストラップやペンダントなどに加工してもらうこともできます。かつて多くの人々が砂金を求めて集った土地で、きらりと光る砂金を探してみましょう。続いては、車でおよそ50分のトキの森公園へ向かいましょう。",
      },
    },
    {
      id: toki.id,
      data: {
        memo: tokiMemo,
        visitTime: new Date(Date.UTC(1970, 0, 1, 13, 35)),
        stayDurationMin: 50,
        transitMode: "car",
        transitDurationMin: 50,
        lat: 38.0372802,
        lng: 138.4219455,
      },
    },
    {
      create: {
        name: "佐渡歴史伝説館",
        address: "佐渡市真野655",
        lat: 37.9546675,
        lng: 138.3462313,
        visitTime: new Date(Date.UTC(1970, 0, 1, 14, 59)),
        stayDurationMin: 95,
        transitMode: "car",
        transitDurationMin: 34,
        memo:
          "トキの森公園からは車でおよそ34分です。佐渡歴史伝説館は、佐渡に流された順徳天皇・日蓮・世阿弥ら歴史上の人物や、島に伝わる伝説を、等身大のロボットを使って紹介する体感型のミュージアムです。昭和48年(1973)の開館以来、佐渡が古くから流刑の地であった歴史を、8つの場面に分けて分かりやすく伝えています。能楽を大成した世阿弥も、晩年をこの佐渡で過ごしたと伝えられており、館内には能舞台も設けられています。冬季は営業時間が異なることがあるため、出かける前に公式サイトで確かめておきましょう。佐渡に流された人々がどのような思いでこの島で過ごしたのか、思いをはせてみましょう。見学を終えたら、レンタカーで港まで戻りましょう。",
      },
    },
  ]);

  for (const [name, mode, min] of [
    ["宿根木集落", "car", 10],
    ["佐渡西三川ゴールドパーク", "car", 20],
    ["トキの森公園", "car", 50],
    ["佐渡歴史伝説館", "car", 34],
  ] as [string, string, number][]) {
    const s = await prisma.spot.findFirstOrThrow({ where: { dayId: day1.id, name } });
    await prisma.spotTransitLeg.deleteMany({ where: { spotId: s.id } });
    await prisma.spotTransitLeg.create({
      data: { spotId: s.id, orderNo: 1, transitMode: mode, transitDurationMin: min },
    });
  }

  const newDescription =
    "佐渡島南部の小木港で乗るたらい舟体験から、船大工の集落・宿根木、砂金採り体験の西三川ゴールドパーク、特別天然記念物トキに出会えるトキの森公園、佐渡の歴史と伝説を伝える佐渡歴史伝説館まで。佐渡ならではの体験と自然、歴史を一日でめぐるプランです。島内は路線バスの本数が少ないため、レンタカーでの移動がおすすめです。";
  await prisma.itinerary.update({ where: { id: ITIN_ID }, data: { description: newDescription } });

  console.log("done");
}
main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
