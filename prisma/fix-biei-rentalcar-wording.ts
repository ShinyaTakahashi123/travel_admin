/**
 * 美瑛(22c9a16c、公開済み)「ケンとメリーの木」の書き出しを、レンタカーの決まり
 * (itinerary-rules.md59行「手続き（約15分）と運転の時間を分けて書く」)の形に直す
 * (2026-11-02企画運営の指示)。時刻・区間(ともに変更なし)はそのまま。
 */
import { prisma } from "../src/lib/prisma";

const commit = process.argv.includes("--commit");
const ITIN_ID = "22c9a16c-f753-481c-b2a1-e2c542feb897";

async function main() {
  console.log(commit ? "=== 書き込みモード ===" : "=== 確認モード(--commitで書き込み) ===");

  const spot = await prisma.spot.findFirstOrThrow({
    where: { name: "ケンとメリーの木", day: { itineraryId: ITIN_ID } },
  });

  const MEMO_OLD =
    "JR美瑛駅からレンタカーで約15分、丘の畑の中にぽつんと立つ一本の木が、この旅のスタートです。一見ポプラと呼ばれることが多いのですが、正式にはセイヨウハコヤナギ、通称イタリアヤマナラシという品種にあたります。1976年に放送された日産スカイライン(4代目)のCM「地図のない旅」のロケ地となり、劇中の主人公カップル「ケン」と「メリー」の名前にちなんでこの愛称で呼ばれるようになりました。樹齢は100年を超え、高さは約30mにも達する堂々とした姿です。木のまわりは今も農家の方が使っている私有地のため、道路から静かに眺め、畑の中へは立ち入らないようにしましょう。この後は、車でおよそ31分、十勝岳望岳台へ向かいましょう。";
  const MEMO_NEW =
    "JR美瑛駅の近くでレンタカーを借りて(手続きに15分ほど)、車でおよそ9分、丘の畑の中にぽつんと立つ一本の木が、この旅のスタートです。一見ポプラと呼ばれることが多いのですが、正式にはセイヨウハコヤナギ、通称イタリアヤマナラシという品種にあたります。1976年に放送された日産スカイライン(4代目)のCM「地図のない旅」のロケ地となり、劇中の主人公カップル「ケン」と「メリー」の名前にちなんでこの愛称で呼ばれるようになりました。樹齢は100年を超え、高さは約30mにも達する堂々とした姿です。木のまわりは今も農家の方が使っている私有地のため、道路から静かに眺め、畑の中へは立ち入らないようにしましょう。この後は、車でおよそ31分、十勝岳望岳台へ向かいましょう。";
  if (spot.memo !== MEMO_OLD) throw new Error("ケンとメリーの木: memo現在値が期待と不一致");

  console.log(`\n旧: ${MEMO_OLD}`);
  console.log(`\n新: ${MEMO_NEW}`);
  console.log("\n時刻・滞在・区間は変更なし(09:30/45分/区間なし=1日目1か所目)");

  if (!commit) {
    console.log("\n前提の確認OK。--commitで書き込みます。");
    return;
  }

  await prisma.spot.update({ where: { id: spot.id }, data: { memo: MEMO_NEW } });
  console.log("書き込みました。");
}
main().finally(() => prisma.$disconnect());
