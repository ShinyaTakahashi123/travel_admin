import { prisma } from "../src/lib/prisma";
import { setDaySpotOrder } from "./lib/spot-order";

const DAY1_ID = "878b6c6c-7d71-4151-a303-edb9ce56d8bd";
const DENSHOKAN_ID = "65523682-1bc5-4218-b924-a0114505b76d";
const SENSHU_ID = "ca8d63be-6d4a-4a16-8dd5-224708d6d4c4";

function t(h: number, m: number) {
  return new Date(Date.UTC(1970, 0, 1, h, m));
}

async function main() {
  const already = await prisma.spot.findFirst({ where: { name: "秋田県立美術館", dayId: DAY1_ID } });
  if (already) {
    console.log("already applied, skipping");
    return;
  }

  const denshokan = await prisma.spot.findFirstOrThrow({ where: { id: DENSHOKAN_ID } });
  const senshu = await prisma.spot.findFirstOrThrow({ where: { id: SENSHU_ID } });

  const denshokanMemo =
    "秋田の歴史と文化をめぐる旅は、秋田市民俗芸能伝承館からスタートです。秋田駅から歩いて15分ほどのこちらは、「ねぶり流し館」の愛称で親しまれる、秋田の伝統行事や民俗芸能を紹介する施設です。「ねぶり流し」とは、夏の眠気や災いを払う「眠り流し」という七夕行事のことで、秋田の夏を彩る竿燈まつりも、この眠り流しの行事に、豊作を願う気持ちが結びついて生まれたと伝えられています。江戸時代の宝暦年間(1751〜1763)ごろ、久保田城下の町人町で始まったとされ、およそ270年の歴史を持つお祭りです。館内には実際にまつりで使われる、稲穂に見立てた提灯が連なる本物の竿燈が展示されており、間近でその迫力を体感できます。見学を終えたら、歩いておよそ15分の千秋公園へ向かいましょう。";

  const senshuMemo =
    "秋田市民俗芸能伝承館からは、歩いておよそ15分です。千秋公園は、秋田藩主・佐竹氏の居城であった久保田城の跡地に整備された公園です。慶長7年(1602)、初代藩主・佐竹義宣がこの地に入り、翌年から築城が始まった久保田城は、財政事情などから石垣や天守を持たない、質実な造りの城であったと伝えられています。今も堀や土塁が残るほか、平成元年(1989)の市制100周年を記念して復元された御隅櫓、佐竹氏ゆかりの史料を展示する佐竹史料館、歴代藩主を祀る彌高神社・八幡秋田神社など、見どころが点在しています。城跡は現在、桜や紅葉の名所として市民に親しまれる公園として整備されています。今も祈りが続く境内の神社では、静かに、敬意をもってお参りください。堀端をゆっくりと歩きながら、秋田藩の歴史に思いを馳せてみましょう。見学を終えたら、歩いておよそ9分の秋田県立美術館へ向かいましょう。";

  await setDaySpotOrder(DAY1_ID, [
    { id: denshokan.id, data: { memo: denshokanMemo } },
    { id: senshu.id, data: { stayDurationMin: 90, memo: senshuMemo } },
    {
      create: {
        name: "秋田県立美術館",
        address: "秋田市中通1-4-2",
        lat: 39.7174373,
        lng: 140.1215722,
        visitTime: t(12, 34),
        stayDurationMin: 90,
        transitMode: "walk",
        transitDurationMin: 9,
        memo:
          "千秋公園からは、歩いておよそ9分です。秋田県立美術館は、複合施設「エリアなかいち」内にある美術館で、建築家・安藤忠雄が設計した建物も見どころの一つです。画家・藤田嗣治の作品を中心に、秋田にゆかりのある美術品を多数収蔵しており、なかでも、縦およそ3.65m、横およそ20.5mにおよぶ大壁画「秋田の行事」は、代表的な所蔵作品です。館内のラウンジや、館に隣接する飲食店で昼食をとるとよいでしょう。大きな吹き抜けのある開放的な空間で、ゆったりと作品を鑑賞しましょう。見学を終えたら、歩いておよそ7分の秋田市立赤れんが郷土館へ向かいましょう。",
      },
    },
    {
      create: {
        name: "秋田市立赤れんが郷土館",
        address: "秋田市大町3-3-21",
        lat: 39.717209,
        lng: 140.115616,
        visitTime: t(14, 11),
        stayDurationMin: 70,
        transitMode: "walk",
        transitDurationMin: 7,
        memo:
          "秋田県立美術館からは、歩いておよそ7分です。秋田市立赤れんが郷土館は、明治45年(1912)に旧秋田銀行本店本館として建てられた建物です。外観はルネサンス様式を基調としたれんが造り、内部はバロック様式を取り入れたつくりで、建物全体が国の重要文化財に指定されています。館内では、秋田の工芸品や、郷土にゆかりのある美術作品などを紹介する展示を見学できます。明治から大正にかけての秋田の近代建築を、じっくりと眺めてみましょう。見学を終えたら、歩いておよそ24分の秋田まるごと市場へ向かいましょう。",
      },
    },
    {
      create: {
        name: "秋田まるごと市場",
        address: "秋田市卸町1-2-7",
        lat: 39.7005003,
        lng: 140.1095555,
        visitTime: t(15, 45),
        stayDurationMin: 60,
        transitMode: "walk",
        transitDurationMin: 24,
        memo:
          "赤れんが郷土館からは、歩いておよそ24分です。秋田まるごと市場は、秋田県内の鮮魚や青果、特産品が並ぶ、地元の人々にも親しまれる市場です。店内には食事処もあり、秋田の魚介や郷土料理を味わうこともできます。秋田ならではの食材や、お土産を探しながら、旅の最後のひとときを楽しみましょう。秋田の伝統文化と歴史、そして食にふれる一日は、ここで終わりです。帰りは、バスでおよそ10分の秋田駅へ向かい、帰路につきましょう。",
      },
    },
  ]);

  console.log("done");
}
main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
