import { prisma } from "../src/lib/prisma";
import { setDaySpotOrder } from "./lib/spot-order";

const DAY1_ID = "ea7873e1-48c0-420d-b828-a83657dfd56a";

const T = (h: number, m: number) => new Date(Date.UTC(1970, 0, 1, h, m));

async function main() {
  const kitagata = await prisma.spot.findFirstOrThrow({ where: { dayId: DAY1_ID, name: "北潟湖" } });
  if (kitagata.memo?.includes("芦原温泉駅で借り")) {
    console.log("already applied, skipping");
    return;
  }

  await setDaySpotOrder(
    DAY1_ID,
    [
      {
        id: kitagata.id,
        data: {
          visitTime: T(9, 0),
          stayDurationMin: 75,
          memo: "レンタカーは芦原温泉駅で借り、車でおよそ15分、あわらの旅は北潟湖から始まります。福井県あわら市と石川県加賀市の境にまたがる、海とつながっていた歴史を持つ湖です。湖畔には「北潟湖ハミングロード」と呼ばれるサイクリングロードが整備されており、豊かな自然の景色を眺めながらのんびりと湖を一周することができます。湖畔公園には、シンボルとなっている歩行者・自転車専用の橋「アイリスブリッジ」が架かり、レンタサイクルや、手漕ぎボート・足こぎボートの貸し出しも行われています(利用期間は季節によって異なります)。水面に映る空と山並みのコントラストは、四季を通じて美しい表情を見せてくれます。風を感じながらのサイクリングで、あわらの自然をゆったりと楽しみましょう。見学を終えたら、車で吉崎御坊へ向かいましょう。",
        },
      },
      {
        create: {
          name: "吉崎御坊",
          address: "あわら市吉崎",
          lat: 36.2876925,
          lng: 136.2525688,
          visitTime: T(10, 23),
          stayDurationMin: 40,
          memo: "北潟湖から車で8分ほど、次に訪れるのは吉崎御坊です。室町時代、浄土真宗の僧・蓮如上人がこの地に坊舎を構え、北陸における布教の拠点としたと伝えられる史跡です。往時の坊舎は失われていますが、国の史跡に指定された高台からは、北潟湖や鹿島の森、日本海まで見渡すことができます。現在は、真宗大谷派と本願寺派、それぞれの別院(東別院・西別院)が建てられています。蓮如上人の像にも手を合わせ、静かに、敬意をもって見学しましょう。見学を終えたら、歩いて蓮如上人記念館へ向かいましょう。",
          transitLegs: { create: [{ orderNo: 1, transitMode: "car", transitDurationMin: 8 }] },
        },
      },
      {
        create: {
          name: "蓮如上人記念館",
          address: "あわら市吉崎1丁目901-1",
          lat: 36.289436,
          lng: 136.251419,
          visitTime: T(11, 6),
          stayDurationMin: 45,
          memo: "吉崎御坊から歩いて3分ほど、次に訪れるのは蓮如上人記念館です。蓮如上人の生涯と、吉崎御坊の歴史を伝える資料館で、直筆の書状や、ジオラマによる再現展示などを見学できます。小川に「幸せ蓮如みくじ」を流す体験や、心静かに写経を楽しめる一角もあります。蓮如上人の足跡に触れながら、ゆっくりと見学しましょう。見学を終えたら、車で昼食の場所へ向かいましょう。",
          transitLegs: { create: [{ orderNo: 1, transitMode: "walk", transitDurationMin: 3 }] },
        },
      },
      {
        create: {
          name: "あわら市内で昼食",
          address: "あわら市",
          lat: 36.215542,
          lng: 136.2353609,
          visitTime: T(12, 1),
          stayDurationMin: 70,
          memo: "蓮如上人記念館から車で10分ほど、お昼はあわら市内で食事をとりましょう。北陸新幹線の開業で賑わう芦原温泉駅の周辺には、食堂やカフェが集まっています。午前中の散策で動いた体を休めながら、ゆっくりと食事を楽しみましょう。お腹を満たしたら、車で東尋坊へ向かいましょう。",
          transitLegs: { create: [{ orderNo: 1, transitMode: "car", transitDurationMin: 10 }] },
        },
      },
      {
        create: {
          name: "東尋坊",
          address: "坂井市三国町安島",
          lat: 36.2378867,
          lng: 136.1256526,
          visitTime: T(13, 46),
          stayDurationMin: 100,
          memo: "あわら市内から車で35分ほど、次に訪れるのは東尋坊です。輝石安山岩の柱状節理が、およそ1kmにわたって続く大規模な海岸で、このような規模の柱状節理は世界に3か所ともいわれ、国の天然記念物・名勝に指定されています。高さ20mを超える断崖が日本海に向かって連なり、波の浸食が作り出した荒々しい景観を間近に見ることができます。断崖沿いの遊歩道を歩きながら、迫力ある景色を眺めましょう。崖の先端は手すりのない場所もあるため、足元に十分気をつけ、立ち入り禁止の場所には入らないようにしましょう。見学を終えたら、車で雄島へ向かいましょう。",
          transitLegs: { create: [{ orderNo: 1, transitMode: "car", transitDurationMin: 35 }] },
        },
      },
      {
        create: {
          name: "雄島",
          address: "坂井市三国町安島",
          lat: 36.2517537,
          lng: 136.1190402,
          visitTime: T(15, 36),
          stayDurationMin: 55,
          memo: "東尋坊から車で10分ほど、旅の最後に訪れるのは雄島です。安島漁港から、朱色の雄島橋を渡って上陸できる、周囲およそ2kmの無人島です。島の南東には大湊神社が祀られ、古くから航海や漁業の守り神として信仰されてきました。柱状節理や板状節理の広がる海沿いの岩肌も見ごたえがあります。静かに、敬意をもって参拝しましょう。見学を終えたら、車で芦原温泉駅へ戻り、レンタカーを返却して、あわらの絶景を巡る旅を締めくくりましょう。",
          transitLegs: { create: [{ orderNo: 1, transitMode: "car", transitDurationMin: 10 }] },
        },
      },
    ]
  );

  console.log("#365: 吉崎御坊・蓮如上人記念館・あわら市内で昼食・東尋坊・雄島を追加、09:00〜16:31着地");
  console.log("done");
}
main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
