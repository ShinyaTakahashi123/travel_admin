/**
 * #368 三徳山三佛寺、断崖絶壁の国宝・投入堂を目指すプラン(ce55cb0f)。
 * 三佛寺(投入堂)1か所・09:00〜11:30のみだったのを、三朝温泉・倉吉市内を
 * 日ノ丸バスと徒歩で回る5か所・09:00〜16:37に組み直す。旧文の古い案内口調
 * (「皆様、本日は」「ご案内いたします」)と、料金・ご了承くださいの文言も直した。
 *
 * - 三佛寺: 既存座標(35.399306,133.95575)はOSMの境内ポリゴン中心と近いため
 *   そのまま使用
 * - 三朝温泉散策・昼食: 株湯(OSM node、35.407622,133.898265、既存DBの値と一致)
 *   を散策の点に、三朝温泉散策マップの点(35.4123103,133.8892382)を昼食の点に使用
 * - 倉吉白壁土蔵群・打吹公園: 既存DBの値(他の公開中のしおりで使用)がOSMの
 *   実際のエリア(打吹公園はOSMのway中心と一致)と近いため、そのまま使用
 *
 * 新しい時刻(09:00〜16:37、5か所):
 * 三佛寺(150)→三朝温泉散策(40)→三朝温泉で昼食(60)→倉吉白壁土蔵群・
 * 打吹玄関通り(90)→打吹公園(60)
 *
 * 実行方法: npm run prod -- npx tsx prisma/fix-368-ce55cb0f.ts
 */
import { prisma } from "../src/lib/prisma";
import { setDaySpotOrder } from "./lib/spot-order";

const DAY1_ID = "ccb88c35-5eb7-4b59-ad40-9cb05a19cf7e";
const ITIN_ID = "ce55cb0f-9bec-4d98-9f46-f05f48e90be1";

const T = (h: number, m: number) => new Date(Date.UTC(1970, 0, 1, h, m));

async function main() {
  const sanbutsuji = await prisma.spot.findFirstOrThrow({ where: { dayId: DAY1_ID, name: "三徳山三佛寺（投入堂）" } });
  if (sanbutsuji.memo?.includes("バスで三朝温泉へ向かいましょう")) {
    console.log("already applied, skipping");
    return;
  }

  await prisma.itinerary.update({
    where: { id: ITIN_ID },
    data: {
      description:
        "断崖の窪みに建てられた、日本一危険な国宝とも言われる投入堂。修験道の聖地・三徳山三佛寺で参拝登山を楽しんだあとは、三朝温泉や倉吉の白壁土蔵群も訪ね歩くプランです。",
    },
  });

  await setDaySpotOrder(DAY1_ID, [
    {
      id: sanbutsuji.id,
      data: {
        memo: "倉吉駅から日ノ丸バスで40分ほど、三朝町の旅は三徳山三佛寺の投入堂参拝登山から始まります。断崖の窪みに建つ奥院・投入堂は、懸造り建築の国宝で、修験道の行者が法力でお堂を投げ入れて建てたと伝えられています。参拝には麓の本堂で受付を済ませ、輪袈裟を着用してから、鎖やロープを使う険しい山道を往復1時間40分ほど歩きます。参拝登山は必ず2人以上で行い、スカートや革靴、サンダル、金具付きの登山靴での入山はできません。雨や雪など天候の悪い日は、入山できないことがあります。足元に気をつけて、ゆっくりと進みましょう。参拝を終えたら、バスで三朝温泉へ向かいましょう。",
      },
    },
    {
      create: {
        name: "三朝温泉散策",
        address: "東伯郡三朝町三朝634-1",
        lat: 35.407622,
        lng: 133.898265,
        visitTime: T(11, 50),
        stayDurationMin: 40,
        memo: "三佛寺からバスで20分ほど、次に訪れるのは三朝温泉です。平安時代から伝わるとされる、世界的にも珍しい高温のラドン温泉です。温泉街の中心に建つ共同浴場「株湯」は、三朝温泉発祥の地とされ、建物の前には飲泉所もあります。すぐそばを流れる三徳川の河原には、川と一体になったような露天風呂も見られます。昭和9年(1934)に架けられた三朝橋をはじめ、温泉情緒の漂う通りを歩いてみましょう。見学を終えたら、歩いてお昼の場所へ向かいましょう。",
        transitLegs: { create: [{ orderNo: 1, transitMode: "bus", transitDurationMin: 20, transitLine: "日ノ丸バス(三徳山線)" }] },
      },
    },
    {
      create: {
        name: "三朝温泉で昼食",
        address: "東伯郡三朝町三朝",
        lat: 35.4123103,
        lng: 133.8892382,
        visitTime: T(12, 43),
        stayDurationMin: 60,
        memo: "三朝温泉の町をそぞろ歩いて13分ほど、お昼は三朝温泉で食事をとりましょう。温泉街には、地元の食材を使った食事処や甘味処が並んでいます。川のせせらぎを聞きながら、ゆっくりと食事を楽しみましょう。お腹を満たしたら、バスで倉吉へ向かいましょう。",
        transitLegs: { create: [{ orderNo: 1, transitMode: "walk", transitDurationMin: 13 }] },
      },
    },
    {
      create: {
        name: "倉吉白壁土蔵群",
        address: "倉吉市東仲町",
        lat: 35.431839,
        lng: 133.823571,
        visitTime: T(14, 3),
        stayDurationMin: 90,
        memo: "三朝温泉からバスで20分ほど、次に訪れるのは倉吉白壁土蔵群です。玉川沿いに、白い漆喰の壁と黒い焼杉板の土蔵、赤い石州瓦の屋根が続く町並みで、江戸時代から明治時代にかけて建てられた商家や土蔵が今も残っています。隣接する打吹玄関通りには、古い町家を生かした店舗が並び、散策や買い物を楽しめます。この一帯には、大坂の豪商「淀屋」ゆかりの商家・倉吉淀屋など、見学できる建物もあります。玉川にかかる赤い石橋を渡りながら、昔ながらの町並みをゆっくりと歩きましょう。見学を終えたら、歩いて打吹公園へ向かいましょう。",
        transitLegs: { create: [{ orderNo: 1, transitMode: "bus", transitDurationMin: 20, transitLine: "日ノ丸バス(三朝温泉⇔倉吉駅)" }] },
      },
    },
    {
      create: {
        name: "打吹公園",
        address: "倉吉市仲ノ町",
        lat: 35.429805,
        lng: 133.823819,
        visitTime: T(15, 37),
        stayDurationMin: 60,
        memo: "倉吉白壁土蔵群から歩いて4分ほど、旅の最後に訪れるのは打吹公園です。明治37年(1904)、当時の皇太子(後の大正天皇)の山陰巡啓を記念して開かれた公園で、桜の名所として知られ、「さくらの名所100選」にも選ばれています。園内には長谷寺などの古い寺院もあり、打吹山の斜面を生かした散策路が整えられています。四季折々の木々を眺めながら、ゆっくりと歩きましょう。見学を終えたら、バスで倉吉駅へ戻り、三朝町・倉吉を巡る1日を締めくくりましょう。",
        transitLegs: { create: [{ orderNo: 1, transitMode: "walk", transitDurationMin: 4 }] },
      },
    },
  ]);

  console.log("#368: 三朝温泉散策・昼食・倉吉白壁土蔵群・打吹公園を追加、09:00〜16:37着地");
  console.log("done");
}
main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
