async function main() {
  const spots = await prisma.spot.findMany({ where: { id: { in: Object.keys(EDITS) } }, include: { day: { select: { itineraryId: true } } } });
  if (spots.length !== Object.keys(EDITS).length || spots.some((s) => !s.day.itineraryId.startsWith("bb3ae76a"))) throw new Error("スポットが想定と違います");
  const memos: Record<string, string> = {};
  for (const [id, edits] of Object.entries(EDITS)) {
    const s = spots.find((x) => x.id === id)!;
    let m = s.memo ?? "";
    for (const e of edits) {
      if (m.split(e.from).length !== 2) throw new Error(`${s.name}: 置き換え元が見つかりません: ${e.from.slice(0, 20)}`);
      m = m.replace(e.from, e.to);
      console.log(`${s.name} → ${e.to}`);
    }
    for (const w of ["ください", "おすすめ", "ぜひ"]) if (m.includes(w)) console.log(`  ⚠ ${s.name}: 「${w}」が残っています`);
    memos[id] = m;
  }
  if (!COMMIT) return console.log("\n確認モードです。--commit で書き込みます。");
  await prisma.$transaction(Object.entries(memos).map(([id, memo]) => prisma.spot.update({ where: { id }, data: { memo } })));
  console.log("\n書き込みました。");
}

main()
