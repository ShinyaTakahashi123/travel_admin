async function main() {
  const spots = await prisma.spot.findMany({ where: { id: { in: [OTOME, YUHODO, SHIMEITEI] } } });
  const byId = new Map(spots.map((s) => [s.id, s]));
  if (byId.get(OTOME)!.memo !== OTOME_MEMO_OLD) throw new Error("乙女の像: memo現在値が期待と不一致");
  if (byId.get(YUHODO)!.memo !== YUHODO_MEMO_OLD) throw new Error("十和田湖畔遊歩道: memo現在値が期待と不一致");
  if (byId.get(SHIMEITEI)!.memo !== SHIMEITEI_MEMO_OLD) throw new Error("紫明亭展望台: memo現在値が期待と不一致");
  console.log("前提の確認OK。\n");
  console.log("[乙女の像] 眺めてみてください。→眺めましょう。");
  console.log("[十和田湖畔遊歩道] 昼食のおすすめ→ゆっくり昼食にしましょう。歩いてください→歩きましょう。");
  console.log("[紫明亭展望台] 持ち帰ってください→ゆっくり眺めましょう。");

  if (!commit) {
    console.log("\n確認モードです。--commit を付けると書き込みます。");
    return;
  }

  await prisma.$transaction([
    prisma.spot.update({ where: { id: OTOME }, data: { memo: OTOME_MEMO_NEW } }),
    prisma.spot.update({ where: { id: YUHODO }, data: { memo: YUHODO_MEMO_NEW } }),
    prisma.spot.update({ where: { id: SHIMEITEI }, data: { memo: SHIMEITEI_MEMO_NEW } }),
  ]);
  console.log("\n書き込みました。");
}

main().finally(() => prisma.$disconnect());
