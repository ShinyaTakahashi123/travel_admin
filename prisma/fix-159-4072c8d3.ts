        memo: "壇上伽藍から歩いて4分ほど、次に訪れるのは六時の鐘です。元和4年(1618)、武将・福島正則が父母の菩提のために寄進したと伝えられる鐘楼です。一度焼失したのち、正保2年(1645)、正則の子・正利によって再建されました。今も高野山に時を告げる鐘として親しまれています。壇上伽藍の一角にひっそりとたたずむ、静かな佇まいも魅力です。見学を終えたら、歩いて門前町へ向かい、お昼を食べましょう。",
