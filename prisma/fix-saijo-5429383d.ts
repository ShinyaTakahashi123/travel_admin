async function main() {
  console.log(commit ? "=== 書き込みモード ===" : "=== 確認モード(--commitで書き込み) ===");

  const spots = await prisma.spot.findMany({ where: { id: { in: Object.values(IDS) } } });
  const byId = new Map(spots.map((s) => [s.id, s]));
  const checks: [string, string, string][] = [
    [IDS.mitate, "御建神社", MITATE_MEMO_OLD],
    [IDS.museum, "東広島市立美術館", MUSEUM_MEMO_OLD],
    [IDS.hakubotan, "白牡丹酒造", HAKUBOTAN_MEMO_OLD],
    [IDS.kamotsuru, "賀茂鶴酒造", KAMOTSURU_MEMO_OLD],
    [IDS.lunch, "西条駅周辺（昼食）", LUNCH_MEMO_OLD],
    [IDS.fukubijin, "福美人酒造", FUKUBIJIN_MEMO_OLD],
    [IDS.kamoizumi, "賀茂泉酒造「酒泉館」", KAMOIZUMI_MEMO_OLD],
    [IDS.kokubunji, "安芸国分寺歴史公園", KOKUBUNJI_MEMO_OLD],
  ];
  for (const [id, label, old] of checks) {
    const s = byId.get(id);
    if (!s) throw new Error(`${label}: スポットが見つかりません`);
    if (s.memo !== old) throw new Error(`${label}: memo現在値が期待と不一致`);
  }

  console.log("\n[新しい時刻・滞在]");
  console.log("①御建神社 09:22(変更なし)/45分(変更なし)");
  console.log("②東広島市立美術館 10:22/65分(変更なし)");
  console.log("③白牡丹酒造 11:32/40分(変更なし)");
  console.log("④賀茂鶴酒造 12:17/40分(変更なし)");
  console.log("⑤西条駅周辺(昼食) 13:01/35分(30分から、下限に届かせる)");
  console.log("⑥福美人酒造 13:42/35分(変更なし)");
  console.log("⑦賀茂泉酒造「酒泉館」 14:22/55分(変更なし)");
  console.log("⑧安芸国分寺歴史公園 15:29/70分(変更なし)、終わり16:39(16:30〜17:00の中)");
  console.log("昼食13:01着(11:30〜13:30内)。legの値は変更なし(すべてOSRMで確認済み)");

  if (!commit) {
    console.log("\n前提の確認OK。--commitで書き込みます。");
    return;
  }

  await prisma.$transaction(async (tx) => {
    await tx.spot.update({ where: { id: IDS.mitate }, data: { memo: MITATE_MEMO_NEW } });
    await tx.spot.update({ where: { id: IDS.museum }, data: { memo: MUSEUM_MEMO_NEW } });
    await tx.spot.update({ where: { id: IDS.hakubotan }, data: { memo: HAKUBOTAN_MEMO_NEW } });
    await tx.spot.update({ where: { id: IDS.kamotsuru }, data: { memo: KAMOTSURU_MEMO_NEW } });
    await tx.spot.update({ where: { id: IDS.lunch }, data: { memo: LUNCH_MEMO_NEW, stayDurationMin: 35 } });
    await tx.spot.update({ where: { id: IDS.fukubijin }, data: { memo: FUKUBIJIN_MEMO_NEW } });
    await tx.spot.update({ where: { id: IDS.kamoizumi }, data: { memo: KAMOIZUMI_MEMO_NEW } });
    await tx.spot.update({ where: { id: IDS.kokubunji }, data: { memo: KOKUBUNJI_MEMO_NEW } });

    // 昼食の滞在が5分のびたため、以降の到着時刻を5分ずらす
    const after = [
      { id: IDS.fukubijin, h: 13, m: 42 },
      { id: IDS.kamoizumi, h: 14, m: 22 },
      { id: IDS.kokubunji, h: 15, m: 29 },
    ];
    for (const a of after) {
      await tx.spot.update({
        where: { id: a.id },
        data: { visitTime: new Date(Date.UTC(1970, 0, 1, a.h, a.m)) },
      });
    }
  });
  console.log("書き込みました。");
}
main().finally(() => prisma.$disconnect());
