const AREA_NAME = "近江八幡";
const AREA_SLUG = "omihachiman";
const AREA_DESCRIPTION =
  "滋賀県近江八幡市は、豊臣秀次が築いた八幡山城の城下町として発展した町です。白壁の土蔵が並ぶ八幡堀や、近江商人の町家が残る新町通り、八幡山からの眺めなど、水郷の景観と商人の歴史を今に伝えています。";

async function ensureArea() {
  const pref = await prisma.area.findFirstOrThrow({ where: { name: "滋賀県", level: "prefecture" } });
  const existing = await prisma.area.findFirst({ where: { parentId: pref.id, name: AREA_NAME } });
  if (existing) {
    console.log(`エリア「${AREA_NAME}」は既にあります(${existing.id})`);
    return;
  }
  if (!process.argv.includes("--commit")) {
    console.log(`[確認] エリア「${AREA_NAME}」(滋賀県)を新規作成します。slug=${AREA_SLUG}`);
    console.log(`  紹介文: ${AREA_DESCRIPTION}`);
    return;
  }
  const area = await prisma.area.create({
    data: { name: AREA_NAME, level: "area", parentId: pref.id, slug: AREA_SLUG, description: AREA_DESCRIPTION },
  });
  console.log(`エリア作成: ${area.name} (${area.id})`);
}

