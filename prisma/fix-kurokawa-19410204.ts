async function main() {
  console.log(commit ? "=== 書き込みモード ===" : "=== 確認モード(--commitで書き込み) ===");

  const itin = await prisma.itinerary.findUniqueOrThrow({ where: { id: ITIN_ID } });
  if (itin.title !== TITLE_OLD) throw new Error("タイトル: 現在値が期待と不一致");
  if (itin.description !== DESC_OLD) throw new Error("説明文: 現在値が期待と不一致");

  const spots = await prisma.spot.findMany({ where: { id: { in: Object.values(IDS) } } });
  const byId = new Map(spots.map((s) => [s.id, s]));
  const checks: [string, string, string][] = [
    [IDS.oshitoishi, "押戸石の丘", OSHITOISHI_MEMO_OLD],
    [IDS.kurokawa, "黒川温泉", KUROKAWA_MEMO_OLD],
    [IDS.senomoto, "瀬の本高原", SENOMOTO_MEMO_OLD],
    [IDS.daikanbo, "大観峰", DAIKANBO_MEMO_OLD],
  ];
  for (const [id, label, old] of checks) {
    const s = byId.get(id);
    if (!s) throw new Error(`${label}: スポットが見つかりません`);
    if (s.memo !== old) throw new Error(`${label}: memo現在値が期待と不一致`);
  }
  if (!byId.has(IDS.tanohara)) throw new Error("田の原温泉: スポットが見つかりません(削除対象)");

  console.log("\n[新しい順番・時刻・滞在・区間]");
  console.log("①押戸石の丘 09:30(09:00から変更)/40分(変更なし)。阿蘇駅レンタカー34分+手続き15分");
  console.log("②黒川温泉(点をバス停に直す) 10:35/90分(180分から分割)/incoming 車25分");
  console.log("③川端通り(新規・昼食) 12:10/40分/incoming 歩5分");
  console.log("④瀬の本高原(点を直す) 13:09/60分(70分から縮める)/incoming 車19分");
  console.log("⑤大観峰(点を直す) 14:43/50分(変更なし)/incoming 車34分");
  console.log("⑥阿蘇神社(新規) 15:57/35分/incoming 車24分、終わり16:32(16:30〜17:00の中)");
  console.log("田の原温泉は削除(行き先として外す)。昼食12:10着(11:30〜13:30内)");

  if (!commit) {
    console.log("\n前提の確認OK。--commitで書き込みます。");
    return;
  }

  await prisma.$transaction(async (tx) => {
    await tx.itinerary.update({ where: { id: ITIN_ID }, data: { title: TITLE_NEW, description: DESC_NEW } });
    await setDaySpotOrder(
      DAY_ID,
      [
        {
          id: IDS.oshitoishi,
          data: { memo: OSHITOISHI_MEMO_NEW, visitTime: t(9, 30) },
        },
        {
          id: IDS.kurokawa,
          data: {
            memo: KUROKAWA_MEMO_NEW,
            visitTime: t(10, 35),
            stayDurationMin: 90,
            lat: 33.0763047,
            lng: 131.1429233,
            transitLegs: { deleteMany: {}, create: [{ orderNo: 1, transitMode: "car", transitDurationMin: 25 }] },
          },
        },
        {
          create: {
            name: "川端通り",
            lat: 33.0780313,
            lng: 131.1416434,
            memo: KAWABATA_MEMO,
            visitTime: t(12, 10),
            stayDurationMin: 40,
            transitLegs: { create: [{ orderNo: 1, transitMode: "walk", transitDurationMin: 5 }] },
          },
        },
        {
          id: IDS.senomoto,
          data: {
            memo: SENOMOTO_MEMO_NEW,
            visitTime: t(13, 9),
            stayDurationMin: 60,
            lat: 33.0856151,
            lng: 131.1930327,
            transitLegs: { deleteMany: {}, create: [{ orderNo: 1, transitMode: "car", transitDurationMin: 19 }] },
          },
        },
        {
          id: IDS.daikanbo,
          data: {
            memo: DAIKANBO_MEMO_NEW,
            visitTime: t(14, 43),
            lat: 32.9956726,
            lng: 131.0670946,
            transitLegs: { deleteMany: {}, create: [{ orderNo: 1, transitMode: "car", transitDurationMin: 34 }] },
          },
        },
        {
          create: {
            name: "阿蘇神社",
            lat: 32.9476916,
            lng: 131.1160299,
            memo: ASOJINJA_MEMO,
            visitTime: t(15, 57),
            stayDurationMin: 35,
            transitLegs: { create: [{ orderNo: 1, transitMode: "car", transitDurationMin: 24 }] },
          },
        },
      ],
      { remove: [IDS.tanohara], tx }
    );
  });
  console.log("書き込みました。");
}
main().finally(() => prisma.$disconnect());
