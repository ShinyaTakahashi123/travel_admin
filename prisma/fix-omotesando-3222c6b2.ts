async function main() {
  console.log(commit ? "=== 書き込みモード ===" : "=== 確認モード(--commitで書き込み) ===");

  const itin = await prisma.itinerary.findUniqueOrThrow({ where: { id: ITIN_ID } });
  if (itin.title !== TITLE_OLD) throw new Error("タイトル: 現在値が期待と不一致");
  if (itin.description !== DESC_OLD) throw new Error("説明文: 現在値が期待と不一致");

  const spots = await prisma.spot.findMany({ where: { id: { in: Object.values(IDS) } } });
  const byId = new Map(spots.map((s) => [s.id, s]));
  const checks: [string, string, string][] = [
    [IDS.nezu, "根津美術館", NEZU_MEMO_OLD],
    [IDS.omotesando, "表参道", OMOTESANDO_MEMO_OLD],
    [IDS.meijijingu, "明治神宮", MEIJIJINGU_MEMO_OLD],
    [IDS.togo, "東郷神社", TOGO_MEMO_OLD],
    [IDS.ota, "太田記念美術館", OTA_MEMO_OLD],
    [IDS.catstreet, "キャットストリート", CATSTREET_MEMO_OLD],
  ];
  for (const [id, label, old] of checks) {
    const s = byId.get(id);
    if (!s) throw new Error(`${label}: スポットが見つかりません`);
    if (s.memo !== old) throw new Error(`${label}: memo現在値が期待と不一致`);
  }
  if (!byId.has(IDS.hikarie)) throw new Error("渋谷ヒカリエ: スポットが見つかりません(削除対象)");

  console.log("\n[新しい順番・時刻・滞在・区間]");
  console.log("①明治神宮(旅の始まり) 09:30/50分。原宿駅から歩き14分");
  console.log("②太田記念美術館 10:35/65分/incoming 歩15分(開館10:30のあと)");
  console.log("③キャットストリート 11:48/40分/incoming 歩8分");
  console.log("④神宮前(新規、昼食) 12:32/40分/incoming 歩4分(11:30〜13:30内)");
  console.log("⑤東郷神社(点を直す) 13:21/45分/incoming 歩9分");
  console.log("⑥表参道 14:15/60分/incoming 歩9分");
  console.log("⑦根津美術館(点を精度よく直す) 15:32/60分/incoming 歩17分(開館10:00のあと)、終わり16:32(16:30〜17:00の中)");
  console.log("渋谷ヒカリエは削除(会社運営の商業ビルが行き先のため)");

  if (!commit) {
    console.log("\n前提の確認OK。--commitで書き込みます。");
    return;
  }

  await prisma.$transaction(async (tx) => {
    await tx.itinerary.update({ where: { id: ITIN_ID }, data: { title: TITLE_NEW, description: DESC_NEW } });
    await setDaySpotOrder(
      DAY_ID,
      [
        { id: IDS.meijijingu, data: { memo: MEIJIJINGU_MEMO_NEW, visitTime: t(9, 30), transitLegs: { deleteMany: {} } } },
        {
          id: IDS.ota,
          data: {
            memo: OTA_MEMO_NEW,
            visitTime: t(10, 35),
            transitLegs: { deleteMany: {}, create: [{ orderNo: 1, transitMode: "walk", transitDurationMin: 15 }] },
          },
        },
        {
          id: IDS.catstreet,
          data: {
            memo: CATSTREET_MEMO_NEW,
            visitTime: t(11, 48),
            transitLegs: { deleteMany: {}, create: [{ orderNo: 1, transitMode: "walk", transitDurationMin: 8 }] },
          },
        },
        {
          create: {
            name: "神宮前",
            lat: 35.6675919,
            lng: 139.7067444,
            memo: JINGUMAE_MEMO,
            visitTime: t(12, 32),
            stayDurationMin: 40,
            transitLegs: { create: [{ orderNo: 1, transitMode: "walk", transitDurationMin: 4 }] },
          },
        },
        {
          id: IDS.togo,
          data: {
            memo: TOGO_MEMO_NEW,
            visitTime: t(13, 21),
            lat: 35.6715318,
            lng: 139.7062108,
            transitLegs: { deleteMany: {}, create: [{ orderNo: 1, transitMode: "walk", transitDurationMin: 9 }] },
          },
        },
        {
          id: IDS.omotesando,
          data: {
            memo: OMOTESANDO_MEMO_NEW,
            visitTime: t(14, 15),
            transitLegs: { deleteMany: {}, create: [{ orderNo: 1, transitMode: "walk", transitDurationMin: 9 }] },
          },
        },
        {
          id: IDS.nezu,
          data: {
            memo: NEZU_MEMO_NEW,
            visitTime: t(15, 32),
            lat: 35.6622429,
            lng: 139.7172555,
            transitLegs: { deleteMany: {}, create: [{ orderNo: 1, transitMode: "walk", transitDurationMin: 17 }] },
          },
        },
      ],
      { remove: [IDS.hikarie], tx }
    );
  });
  console.log("書き込みました。");
}
