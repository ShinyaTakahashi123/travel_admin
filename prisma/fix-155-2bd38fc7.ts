/**
 * #155(航空科学博物館と展望デッキ、空港の街・成田を満喫するファミリープラン、2bd38fc7)
 * を4か所以上・9:30〜16:35に組み直す。
 *
 * 元は航空科学博物館(9:30,100分)→成田国際空港展望デッキ(11:40,60分、
 * 時刻の計算も合っていなかった)の2か所だけで12:40終了(4か所未満・終了
 * 時刻ともに決まり違反)。旧文の「皆様」「ご案内」「お楽しみください」など
 * の案内口調も直した。
 *
 * 航空科学博物館は開館が10:00から(WebSearchで確認)のため、9:30には
 * 入館できない。そこで、1か所目を屋外でいつでも入れるさくらの山にし、
 * 博物館は2か所目(10:10着、開館後)にした。
 *
 * 追加・組み直した内容(すべてOSM実点、車移動。空港第2ビル駅前で
 * レンタカーを借り、最後にターミナルで返す想定):
 * - さくらの山(成田市駒井野、35.7762430,140.3636902)を1か所目に追加
 * - 航空科学博物館(既存)の座標を、OSM実点に合わせて修正
 *   (35.738453,140.396896 → 35.7400338,140.3976040)
 * - 成田国際空港第2ターミナルで昼食(新設、35.7729542,140.3886359)
 * - 成田国際空港展望デッキ(既存)を「第2ターミナル展望デッキ」に改称し、
 *   座標を第2ターミナルの実点に修正(35.7649,140.38845 → 35.7729542,140.3886359。
 *   元の座標はむしろ第1ターミナルに近かった)
 * - 成田国際空港第1ターミナル展望デッキ(新設、35.7630960,140.3863713)を
 *   最後に追加。2026年4月にリニューアルした「SHIKISAI GARDEN」で、
 *   足湯・マウンテンデッキ・キッズエリア・フードコートがある
 *   (出典: https://www.narita-airport.jp/ja/topics/shikisaigarden/ )
 *
 * 新しい時刻(09:30〜16:35、5か所):
 * さくらの山09:30(25)→航空科学博物館10:10(120)→
 * 昼食(第2ターミナル)12:25(70)→第2ターミナル展望デッキ13:38(35)→
 * 第1ターミナル展望デッキ14:25(130)
 *
 * 実行方法: npm run prod -- npx tsx prisma/fix-155-2bd38fc7.ts
 */
import { prisma } from "../src/lib/prisma";
import { setDaySpotOrder } from "./lib/spot-order";

const ITIN_ID = "2bd38fc7-fda8-40a1-b9d2-5df16bb624fd";
const DAY1_ID = "c45d8cd1-2b3e-4d6f-9988-ede8fb90e82d";

const T = (h: number, m: number) => new Date(Date.UTC(1970, 0, 1, h, m));

async function main() {
  const museum = await prisma.spot.findFirstOrThrow({ where: { dayId: DAY1_ID, name: "航空科学博物館" } });
  const deck = await prisma.spot.findFirstOrThrow({ where: { dayId: DAY1_ID, name: "成田国際空港展望デッキ" } });

  if (museum.stayDurationMin === 120) {
    console.log("already applied, skipping");
    return;
  }

  await prisma.itinerary.update({
    where: { id: ITIN_ID },
    data: {
      description:
        "成田国際空港に隣接する航空科学博物館や、離着陸を間近で見られるさくらの丘、空港ターミナルの展望デッキ・足湯も楽しめる「SHIKISAI GARDEN」まで、飛行機好き親子にぴったりの、空港の街・成田をめぐるファミリープランです。",
    },
  });

  await setDaySpotOrder(DAY1_ID, [
    {
      create: {
        name: "さくらの山",
        address: "成田市駒井野",
        lat: 35.776243,
        lng: 140.36369,
        visitTime: T(9, 30),
        stayDurationMin: 25,
        memo: "空港第2ビル駅前でレンタカーを借り、車でおよそ15分、成田の旅はさくらの山から始まります。成田国際空港の滑走路の北側に広がる高台の公園で、「飛行機が見える丘」として親しまれ、離着陸する航空機を間近に見ることができます。テレビドラマのロケ地としても使われてきました。春には、園内に植えられた桜越しに飛行機を眺められる、この丘ならではの景色も楽しめます。芝生の広場でゆっくりと過ごしながら、飛行機を見上げてみましょう。見学を終えたら、車で航空科学博物館へ向かいましょう。",
      },
    },
    {
      id: museum.id,
      data: {
        lat: 35.7400338,
        lng: 140.397604,
        visitTime: T(10, 10),
        stayDurationMin: 120,
        memo: "さくらの山から車でおよそ15分、次に訪れるのは航空科学博物館です。成田国際空港の開港を機に、航空への理解を広めようと平成元年(1989)に開館した、日本で最初の航空専門博物館とされています。館内には、ボーイング747型機の実物エンジンや主翼の一部、客室の輪切り模型などが展示され、間近で機体の構造を学べます。屋外には、戦後初の国産旅客機YS-11の試作1号機も展示されており、日本の航空技術の歴史を体感できます。フライトシミュレーターなどの体験コーナーもあわせて、空港の街ならではの時間をじっくりと楽しみましょう。見学を終えたら、車で成田国際空港第2ターミナルへ向かいましょう。",
        transitLegs: { create: [{ orderNo: 1, transitMode: "car", transitDurationMin: 15 }] },
      },
    },
    {
      create: {
        name: "成田国際空港第2ターミナルで昼食",
        address: "成田市古込1-1",
        lat: 35.7729542,
        lng: 140.3886359,
        visitTime: T(12, 25),
        stayDurationMin: 70,
        memo: "航空科学博物館から車でおよそ15分、お昼は成田国際空港第2ターミナルで食事をとりましょう。保安検査の外側にあるこの4階には、フードコートをはじめ、和食から洋食まで、さまざまな飲食店が並んでいます。航空券がなくても利用できるので、家族そろって好みの店を選べます。空港ならではの賑わいを感じながら、ゆっくりと食事をとりましょう。お腹を満たしたら、歩いて展望デッキへ向かいましょう。",
        transitLegs: { create: [{ orderNo: 1, transitMode: "car", transitDurationMin: 15 }] },
      },
    },
    {
      id: deck.id,
      data: {
        name: "成田国際空港第2ターミナル展望デッキ",
        lat: 35.7729542,
        lng: 140.3886359,
        visitTime: T(13, 38),
        stayDurationMin: 35,
        memo: "成田国際空港第2ターミナルから歩いて3分ほど、次に訪れるのは展望デッキです。滑走路を離着陸する航空機を間近に眺めることができ、轟音とともに大空へ飛び立つ飛行機の姿は迫力満点です。日本各地、そして世界各国へと飛び立つ飛行機を眺めながら、旅情に浸るひとときを過ごしましょう。見学を終えたら、車で第1ターミナルへ向かいましょう。",
        transitLegs: { deleteMany: {}, create: [{ orderNo: 1, transitMode: "walk", transitDurationMin: 3 }] },
      },
    },
    {
      create: {
        name: "成田国際空港第1ターミナル展望デッキ",
        address: "成田市古込1-1",
        lat: 35.763096,
        lng: 140.3863713,
        visitTime: T(14, 25),
        stayDurationMin: 130,
        memo: "成田国際空港第2ターミナル展望デッキから車でおよそ12分、成田の旅の最後に訪れるのは、第1ターミナルの「SHIKISAI GARDEN」です。令和8年(2026)にリニューアルした、5階の展望デッキを含むエリアで、足湯につかりながら、高い位置の「マウンテンデッキ」から航空機の離着陸を眺められます。フードコートや、子ども向けの遊び場もあり、家族でゆっくりと過ごせます。水のせせらぎや緑に囲まれた、空港とは思えない開放的な空間で、旅の締めくくりのひとときを楽しみましょう。見学を終えたら、レンタカーを返して、京成線・JR線で帰りましょう。",
        transitLegs: { create: [{ orderNo: 1, transitMode: "car", transitDurationMin: 12 }] },
      },
    },
  ]);

  console.log("#155: 4か所未満・終了時刻を是正。5か所・09:30〜16:35に組み直し");
  console.log("done");
}
main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
