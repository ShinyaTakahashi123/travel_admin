/**
 * #28 三峯神社の霧海と気運(15185f58) ラウンド4: 文だけの直し
 *
 * 法務の指摘: 道の駅あらかわの宿への一文「今夜は秩父市街の宿へ車でおよそ14分向かい、
 * 旅の1日目を締めくくりましょう。」の「締めくくり」は、決まり(itinerary-rules.md
 * 79行目)で旅の最後のスポットだけに置く言葉のため、1日目には使えない。
 * 「この夜は、車でおよそ14分の秩父市街の宿に泊まりましょう。」に直す。
 * 文だけの直しで、時刻・移動・座標は変更しない。
 */
import { prisma } from "../src/lib/prisma";

const commit = process.argv.includes("--commit");

const MICHINOEKI_ARAKAWA = "76e4d961-43af-4548-991b-9e5fab90bbde";

const MEMO_OLD =
  "三峯神社から車でおよそ56分、旅の1日目最後に訪れるのは道の駅あらかわです。国道140号沿いにあるこの道の駅では、地元・荒川地区で採れた旬の野菜や果物、そばを使ったかりんとうや饅頭、行者ニンニクといった特産品が並ぶ直売所をのぞくことができます。自然体験やクラフトワークショップを行う「山里自然館」も併設され、レストラン「鈴ひろ庵」では地場野菜を使った麺類や、季節のフルーツを使ったソフトクリームも味わえます。秩父の山里ならではのお土産探しに、ゆっくりと立ち寄りましょう。今夜は秩父市街の宿へ車でおよそ14分向かい、旅の1日目を締めくくりましょう。";
const MEMO_NEW =
  "三峯神社から車でおよそ56分、旅の1日目最後に訪れるのは道の駅あらかわです。国道140号沿いにあるこの道の駅では、地元・荒川地区で採れた旬の野菜や果物、そばを使ったかりんとうや饅頭、行者ニンニクといった特産品が並�ぶ直売所をのぞくことができます。自然体験やクラフトワークショップを行う「山里自然館」も併設され、レストラン「鈴ひろ庵」では地場野菜を使った麺類や、季節のフルーツを使ったソフトクリームも味わえます。秩父の山里ならではのお土産探しに、ゆっくりと立ち寄りましょう。この夜は、車でおよそ14分の秩父市街の宿に泊まりましょう。";

async function main() {
  const s = await prisma.spot.findUnique({ where: { id: MICHINOEKI_ARAKAWA } });
  if (!s) throw new Error("道の駅あらかわが見つかりません");
  if (s.memo !== MEMO_OLD) throw new Error("道の駅あらかわ: memo現在値が期待と不一致");

  console.log("前提の確認OK。\n");
  console.log("道の駅あらかわ: 「今夜は秩父市街の宿へ車でおよそ14分向かい、旅の1日目を締めくくりましょう。」→「この夜は、車でおよそ14分の秩父市街の宿に泊まりましょう。」に修正");

  if (!commit) {
    console.log("\n確認モードです。--commit を付けると書き込みます。");
    return;
  }

  await prisma.spot.update({ where: { id: MICHINOEKI_ARAKAWA }, data: { memo: MEMO_NEW } });
  console.log("\n書き込みました。");
}

main().finally(() => prisma.$disconnect());
