async function main() {
  const spots = await prisma.spot.findMany({ where: { day: { itineraryId: ITINERARY_ID } } });
  for (const p of PLAN) {
    const s = spots.find((x) => x.id === p.id);
    if (!s || s.name !== p.name) throw new Error(`${p.name} が見つからない（${s?.name}）`);
    console.log(`${p.name}（${p.memo.length}字）:\n  ${p.memo}\n`);
  }
  if (!COMMIT) return console.log("確認モードです。--commit で書き込みます。");
  await prisma.$transaction(async (tx) => {
    for (const p of PLAN) await tx.spot.update({ where: { id: p.id }, data: { memo: p.memo } });
  });
  console.log("書き込みました。");
}

main()
