async function assertCurrentState() {
  const spots = await prisma.spot.findMany({
    where: {
      id: {
        in: [
          GOSHO, TOWER, SANJUSANGENDO, MUSEUM, HOKOKU,
          SHINKYOGOKU, KAWARAMACHI, PONTOCHO, KAMOGAWA, HEIAN_JINGU, KYOCERA,
        ],
      },
    },
    select: { id: true, visitTime: true, stayDurationMin: true, memo: true },
  });
  const byId = new Map(spots.map((s) => [s.id, s]));

  const checks: [string, string, number, string][] = [
    [GOSHO, "09:00", 60, GOSHO_MEMO_OLD],
    [TOWER, "11:42", 68, TOWER_MEMO_OLD],
    [SANJUSANGENDO, "13:10", 68, ""],
    [MUSEUM, "14:23", 94, MUSEUM_MEMO_OLD],
    [HOKOKU, "16:02", 20, HOKOKU_MEMO_OLD],
    [SHINKYOGOKU, "09:00", 77, SHINKYOGOKU_MEMO_OLD],
    [KAWARAMACHI, "10:22", 77, KAWARAMACHI_MEMO_OLD],
    [PONTOCHO, "11:44", 94, PONTOCHO_MEMO_OLD],
    [KAMOGAWA, "13:23", 94, KAMOGAWA_MEMO_OLD],
    [HEIAN_JINGU, "15:07", 51, HEIAN_JINGU_MEMO_OLD],
    [KYOCERA, "16:03", 45, KYOCERA_MEMO_OLD],
  ];
  for (const [id, hhmm, stay, memo] of checks) {
    const s = byId.get(id);
    if (!s) throw new Error(`spot not found: ${id}`);
    const [h, m] = hhmm.split(":").map(Number);
    const expected = t(h, m).toISOString();
    if (s.visitTime?.toISOString() !== expected) {
      throw new Error(`${id}: visitTime mismatch. 現在値=${s.visitTime?.toISOString()} 期待値=${expected}`);
    }
    if (s.stayDurationMin !== stay) {
      throw new Error(`${id}: stayDurationMin mismatch. 現在値=${s.stayDurationMin} 期待値=${stay}`);
    }
    if (memo && s.memo !== memo) {
      throw new Error(`${id}: memo mismatch.\n現在値: ${s.memo}`);
    }
  }
}

