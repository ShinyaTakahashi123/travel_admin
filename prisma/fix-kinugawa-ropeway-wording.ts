import { prisma } from "../src/lib/prisma";

const commit = process.argv.includes("--commit");

const ID = "9e315f16-fbb7-47c4-a0a6-33a019e9879a";
const NAME = "鬼怒川温泉ロープウェイ";
const OLD_MEMO =
  "龍王峡からタクシーでおよそ9分、鬼怒川温泉の山あいに着きます。鬼怒川温泉ロープウェイは、標高差およそ300mを3分半ほどで結ぶロープウェイで、山頂の展望台からは、鬼怒川沿いに広がる温泉街のレトロな街並みや渓谷美、遠くには筑波山系の山並みまで見渡せます。点検などで運休することがあるので、運行状況を公式サイトで確かめましょう。山頂エリアには、間近でニホンザルを観察できる「おさるの山」や、温泉神社もあります。おさるの山では、決められた場所以外でえさをあげたり、サルに近づきすぎたりしないようにしましょう。山の上から、今回めぐった日光・奥日光・湯西川の景色を振り返りましょう。この後は、ロープウェイで下り、タクシーでおよそ9分の鬼怒太の湯へ向かいましょう。";
const NEW_MEMO =
  "龍王峡からタクシーでおよそ9分、鬼怒川温泉の山あいに着きます。鬼怒川温泉ロープウェイは、標高差およそ300mを3分半ほどで結ぶロープウェイで、山頂の展望台からは、鬼怒川沿いに広がる温泉街のレトロな街並みや渓谷美、遠くには筑波山系の山並みまで見渡せます。雪の日は除雪のため、運転の始まりが遅れることがあります。運行の状況を確かめましょう。山頂エリアには、間近でニホンザルを観察できる「おさるの山」や、温泉神社もあります。おさるの山では、決められた場所以外でえさをあげたり、サルに近づきすぎたりしないようにしましょう。山の上から、今回めぐった日光・奥日光・湯西川の景色を振り返りましょう。この後は、ロープウェイで下り、タクシーでおよそ9分の鬼怒太の湯へ向かいましょう。";

async function main() {
  console.log(commit ? "=== 書き込みモード ===" : "=== 確認モード(--commitで書き込み) ===");
  const spot = await prisma.spot.findUniqueOrThrow({ where: { id: ID } });
  if (spot.name !== NAME) throw new Error(`name不一致: ${spot.name}`);
  if (spot.memo !== OLD_MEMO) throw new Error("memo現在値が期待と不一致");
  console.log(`[${NAME}]\n旧: ${OLD_MEMO}\n\n新: ${NEW_MEMO}`);

  if (!commit) {
    console.log("\n前提の確認OK。--commitで書き込みます。");
    return;
  }
  await prisma.spot.update({ where: { id: ID }, data: { memo: NEW_MEMO } });
  console.log("書き込みました。");
}
main().finally(() => prisma.$disconnect());
