/**
 * #161の続き。他の小豆島の既存プラン2本(03a50000 寒霞渓…、6ad59c82
 * エンジェルロード…)の現在の本文を確認したところ、同じ場所を使った
 * 6か所のうち、文の組み立てや結びが近すぎる箇所が複数見つかったため、
 * 書き出しの事実・結びの言い回しを変えて書き直した(文の重なりの
 * 点検のセルフチェック。企画運営・法務に報告する前に自分で直した)。
 *
 * ①土渕海峡: 「幅9.93m→ギネス認定→横断証明書→橋を渡って体験」という
 *   03a50000・6ad59c82と同じ順番の組み立てだったのを、名前の由来
 *   (土庄の「土」+渕崎の「渕」)から始める構成に変更。
 * ②迷路のまち: 「海賊から守るために道を入り組ませた」という
 *   03a50000と同じ起源説明を結びの「地図を片手に迷いながら歩く」も
 *   含めてほぼ同じ構成だったのを、瀬戸内国際芸術祭のアート作品を
 *   前面に出す構成に変更。
 * ③中山千枚田: 結びの「幾重にも連なる/重なる…里山風景を眺めましょう」が
 *   6ad59c82とほぼ同じ言い回しだったため、季節の彩りの話に変更。
 * ④小豆島オリーブ公園: 「瀬戸内海の青とのコントラストが地中海(エーゲ海)を
 *   思わせる景観」という文の構造が6ad59c82と同じ型だったため、
 *   「写真が撮れる」という結びの形に変更。
 * ⑤二十四の瞳映画村: 「大正から昭和初期の雰囲気を再現した…建物が立ち並び」
 *   が6ad59c82とほぼ同じ言い回しだったため、分校の教室に残る備品の
 *   話に変更。
 * ⑥岬の分教場: 「映画村のセットとは違い、本物の校舎です」という結びの
 *   対比が03a50000とほぼ同じ言い回しだったため、戦争の時代にも子どもが
 *   通っていたという、映画村で先に読んだ物語の時代背景と結びつける
 *   形に変更。
 *
 * 実行方法: npm run prod -- npx tsx prisma/fix-161d-464a25fa.ts
 */
import { prisma } from "../src/lib/prisma";

const DAY1_ID = "322356ed-3fb4-4c5a-afe4-edc2b31855a8";
const DAY2_ID = "c9f825d6-5aa0-4e33-b608-cfcadc4977f3";

async function main() {
  const kaikyo = await prisma.spot.findFirstOrThrow({ where: { dayId: DAY1_ID, name: "土渕海峡" } });
  const meiro = await prisma.spot.findFirstOrThrow({ where: { dayId: DAY1_ID, name: "迷路のまち" } });
  const tanada = await prisma.spot.findFirstOrThrow({ where: { dayId: DAY1_ID, name: "中山千枚田" } });
  const olive = await prisma.spot.findFirstOrThrow({ where: { dayId: DAY1_ID, name: "小豆島オリーブ公園" } });
  const eigamura = await prisma.spot.findFirstOrThrow({ where: { dayId: DAY2_ID, name: "二十四の瞳映画村" } });
  const bunkyojo = await prisma.spot.findFirstOrThrow({ where: { dayId: DAY2_ID, name: "岬の分教場" } });

  if (!kaikyo.memo?.includes("世界一狭い海峡としてギネス世界記録に認定されています")) {
    console.log("already applied, skipping");
    return;
  }

  await prisma.spot.update({
    where: { id: kaikyo.id },
    data: {
      memo: "フェリーで土庄港に着いたら、レンタカーを借りて、小豆島の旅は土渕海峡から始まります。「土渕」という名前は、前島側の土庄地区の「土」と、本島側の渕崎地区の「渕」という、海峡を挟む2つの地区の名前から付けられたと伝えられています。この海峡、幅がもっとも狭いところではわずか9.93mしかなく、世界一狭い海峡としてギネス世界記録に認定されている、ユニークな場所です。海峡にかかる橋を渡って、両岸を行き来してみましょう。見学を終えたら、歩いて迷路のまちへ向かいましょう。",
    },
  });

  await prisma.spot.update({
    where: { id: meiro.id },
    data: {
      memo: "土渕海峡から歩いてすぐ、次に訪れるのは迷路のまちです。土庄の旧市街に広がる、幅1mに満たない路地が網の目のように入り組む町並みで、瀬戸内国際芸術祭の会場の一つにもなっており、空き家や古い蔵を生かした現代アートの作品が路地のあちこちに点在しています。古い町家を利用したカフェや雑貨店も点在し、アートを探しながら歩くだけでも時間を忘れてしまいます。住まいの路地なので、家の敷地には入らず、静かに歩きましょう。見学を終えたら、歩いてお昼を食べに行きましょう。",
    },
  });

  await prisma.spot.update({
    where: { id: tanada.id },
    data: {
      memo: "土庄の町から車でおよそ20分、次に訪れるのは中山千枚田です。山あいの斜面におよそ770枚の田んぼが連なる棚田で、「日本の棚田百選」にも選ばれています。たびたび渇水に見舞われてきた小豆島で、中山地区の人々が力を合わせて切り開いてきた棚田で、湧き水を利用した「湯船の水」が、今も田を潤しています。田植えの時期には水面がきらめき、稲刈りの頃には黄金色に染まるなど、季節ごとに違う彩りを見せてくれます。見学を終えたら、車で小豆島オリーブ公園へ向かいましょう。",
    },
  });

  await prisma.spot.update({
    where: { id: olive.id },
    data: {
      memo: "中山千枚田から車でおよそ15分、次に訪れるのは小豆島オリーブ公園です。日本で初めてオリーブの栽培と搾油に成功したのがこの小豆島で、明治41年(1908)、アメリカから輸入された苗木を植えたことがその始まりと伝えられています。公園のシンボルとして親しまれている白いギリシャ風車は、小豆島と姉妹島提携を結ぶギリシャのミロス島との友好の証として、平成4年(1992)に建てられたものです。実写映画「魔女の宅急便」のロケ地にもなり、風車を背景にほうきにまたがって記念撮影ができるコーナーも人気です。園内には今も2000本を超えるオリーブの木が栽培され、オリーブ記念館やハーブ館ミロスもあわせて見学できます。見学を終えたら、今夜はこの近くの宿に宿泊します。",
    },
  });

  await prisma.spot.update({
    where: { id: eigamura.id },
    data: {
      memo: "宿から車でおよそ15分、旅の2日目は二十四の瞳映画村から始まります。小豆島出身の作家・壺井栄が昭和27年(1952)に発表した小説『二十四の瞳』は、瀬戸内海沿いの小さな村を舞台に、新任の女性教師と12人の教え子たちの絆と、戦争がもたらす悲しみを描いた作品です。物語の舞台は明記されていませんが、その描写と作者の故郷であることから、小豆島がロケ地に選ばれ、昭和62年(1987)の映画化の際に使われたオープンセットが、今も映画村として保存・公開されています。再現された教室には、当時の机やオルガン、黒板が置かれ、物語の時代にタイムスリップしたような気分を味わえます。見学を終えたら、歩いて岬の分教場へ向かいましょう。",
    },
  });

  await prisma.spot.update({
    where: { id: bunkyojo.id },
    data: {
      memo: "映画村から歩いて8分ほど、次に訪れるのは岬の分教場です。正式には苗羽小学校田浦分校といい、明治35年(1902)に建てられ、昭和46年(1971)まで実際に使われていた木造校舎です。映画村で見た分校のセットのいわば本物にあたる建物で、さきほど読んだ物語の時代、そして日本が戦争の時代を迎えたときも、この教室で子どもたちが学んでいました。当時のままの机やオルガンが残る教室を見学できます。見学を終えたら、車でお昼を食べに行きましょう。",
    },
  });

  console.log("#161続き: 他の小豆島プランと文が近かった6か所(土渕海峡・迷路のまち・中山千枚田・オリーブ公園・映画村・岬の分教場)を、書き出し・結びの言い回しを変えて書き直し");
  console.log("done");
}
main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
