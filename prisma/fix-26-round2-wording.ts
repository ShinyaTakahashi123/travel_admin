async function main() {
  const spots = await prisma.spot.findMany({
    where: { id: { in: [ASUKA_JINJA, KAMIKURA_JINJA, SHINGU_STATION] } },
  });
  const byId = new Map(spots.map((s) => [s.id, s]));

  if (byId.get(ASUKA_JINJA)!.memo !== ASUKA_JINJA_MEMO_OLD) throw new Error("阿須賀神社: memo現在値が期待と不一致");
  if (byId.get(KAMIKURA_JINJA)!.memo !== KAMIKURA_JINJA_MEMO_OLD) throw new Error("神倉神社: memo現在値が期待と不一致");
  if (byId.get(SHINGU_STATION)!.memo !== SHINGU_STATION_MEMO_OLD) throw new Error("新宮駅: memo現在値が期待と不一致");

  console.log("前提の確認OK。\n");
  console.log("阿須賀神社・神倉神社: 「お過ごしましょう」→決まりの祈りの一文「今も祈りが続く場所ですので、静かに、敬意をもってお参りしましょう。」に修正");
  console.log("新宮駅: 「ここで、新宮の町なかで昼食をとりましょう」→「新宮駅のまわりで、昼食をとりましょう。」に修正(「で」の重なりを解消)");

  if (!commit) {
    console.log("\n確認モードです。--commit を付けると書き込みます。");
    return;
  }

  await prisma.$transaction(async (tx) => {
    await tx.spot.update({ where: { id: ASUKA_JINJA }, data: { memo: ASUKA_JINJA_MEMO_NEW } });
    await tx.spot.update({ where: { id: KAMIKURA_JINJA }, data: { memo: KAMIKURA_JINJA_MEMO_NEW } });
    await tx.spot.update({ where: { id: SHINGU_STATION }, data: { memo: SHINGU_STATION_MEMO_NEW } });
  });
  console.log("\n書き込みました。");
}

main().finally(() => prisma.$disconnect());
