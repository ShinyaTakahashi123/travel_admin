async function main() {
  const itinId = "0d8b6309-1776-44a6-906c-e98a8e99e538";
  const dayId = "029daf0f-2efb-4051-9dfd-2969e5f97cc9";
  const nyoirinjiId = "90e5d86b-9a0b-4d7b-b999-83c39f63fa83";
  const yoshimizuId = "e9b57519-3f22-425f-9879-d4bffa1940b1";
  const kinpusenId = "28c481ad-92f6-4781-89e6-df5075865f3b";

  console.log("確認OK");
  if (!COMMIT) return console.log("確認モードです。--commit で書き込みます。");

  await prisma.$transaction(async (tx) => {
    await tx.itinerary.update({ where: { id: itinId }, data: { description: DESCRIPTION } });

    const day1: SpotOrderItem[] = [
      { id: nyoirinjiId, data: { visitTime: t(9, 40), stayDurationMin: 45, memo: NYOIRINJI_MEMO } },
      {
        id: yoshimizuId,
        data: {
          visitTime: t(10, 35), stayDurationMin: 40, memo: YOSHIMIZU_MEMO,
          transitLegs: { deleteMany: {}, create: [{ orderNo: 1, transitMode: "walk", transitDurationMin: 10 }] },
        },
      },
      {
        id: kinpusenId,
        data: {
          visitTime: t(11, 25), stayDurationMin: 60, memo: KINPUSEN_MEMO,
          transitLegs: { deleteMany: {}, create: [{ orderNo: 1, transitMode: "walk", transitDurationMin: 10 }] },
        },
      },
      {
        create: {
          name: "賀名生の里歴史民俗資料館", lat: 34.2985494, lng: 135.7196427,
          visitTime: t(13, 0), stayDurationMin: 100, memo: KANAU_MEMO,
          transitLegs: { create: [{ orderNo: 1, transitMode: "car", transitDurationMin: 35 }] },
        },
      },
      {
        create: {
          name: "栄山寺", lat: 34.3559366, lng: 135.7208895,
          visitTime: t(14, 55), stayDurationMin: 95, memo: EISANJI_MEMO,
          transitLegs: { create: [{ orderNo: 1, transitMode: "car", transitDurationMin: 15 }] },
        },
      },
    ];
    await setDaySpotOrder(dayId, day1, { tx });
  }, { timeout: 60000 });

  console.log("COMMITTED");
}
main().finally(() => prisma.$disconnect());
