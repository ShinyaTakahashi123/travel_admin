async function main() {
  const commit = process.argv.includes("--commit");
  console.log(commit ? "登録モードで実行します" : "確認モードで実行します（DBには書き込みません）");

  const names = Object.keys(DESCRIPTIONS);
  const areas = await prisma.area.findMany({ where: { name: { in: names } }, select: { id: true, name: true, level: true, description: true } });
  const found = new Set(areas.map((a) => a.name));
  const missing = names.filter((n) => !found.has(n));
  if (missing.length > 0) console.log(`\n⚠️ 見つからないエリア名: ${missing.join(", ")}`);

  for (const area of areas) {
    const next = DESCRIPTIONS[area.name];
    console.log(`\n■ [${area.level}] ${area.name}（${next.length}字）`);
    console.log(`  ${next}`);
  }

  if (!commit) {
    console.log(`\n対象: ${areas.length}件。確認モードのため、ここで終了します。問題なければ --commit を付けて実行してください。`);
    return;
  }

  for (const area of areas) {
    await prisma.area.update({ where: { id: area.id }, data: { description: DESCRIPTIONS[area.name] } });
  }
  console.log(`\n登録しました: ${areas.length}件`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
