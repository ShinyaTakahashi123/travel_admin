async function main() {
  console.log(commit ? "=== 書き込みモード ===" : "=== 確認モード(--commitで書き込み) ===");

  const itin = await prisma.itinerary.findUniqueOrThrow({ where: { id: ITIN_ID } });
  if (itin.title !== TITLE_OLD) throw new Error("タイトル: 現在値が期待と不一致");
  if (itin.description !== DESC_OLD) throw new Error("説明文: 現在値が期待と不一致");

  const spots = await prisma.spot.findMany({ where: { id: { in: Object.values(IDS) } } });
  const byId = new Map(spots.map((s) => [s.id, s]));
  const checks: [string, string, string][] = [
    [IDS.castle, "高松城跡（玉藻公園）", CASTLE_MEMO_OLD],
    [IDS.shoutengai, "高松中央商店街（讃岐うどん）", SHOUTENGAI_MEMO_OLD],
    [IDS.yashima, "屋島", YASHIMA_MEMO_OLD],
    [IDS.shikokumura, "四国村ミウゼアム", SHIKOKUMURA_MEMO_OLD],
    [IDS.museum, "香川県立ミュージアム", MUSEUM_MEMO_OLD],
  ];
  for (const [id, label, old] of checks) {
    const s = byId.get(id);
    if (!s) throw new Error(`${label}: スポットが見つかりません`);
    if (s.memo !== old) throw new Error(`${label}: memo現在値が期待と不一致`);
  }

  console.log("\n[新しい時刻・滞在・区間]");
  console.log("①高松城跡(旅の始まり) 08:30/60分(変更なし)。高松駅から歩き11分");
  console.log("②高松中央商店街 09:45/45分(60分から縮める、昼食を外す)/incoming 歩15分");
  console.log("③屋島 11:23/90分(変更なし)/incoming 歩15分+手続き15分+車23分(3区間、高松駅でレンタカー)");
  console.log("④屋島山上(新規、昼食) 12:59/40分/incoming 歩6分(11:30〜13:30内)");
  console.log("⑤四国村ミウゼアム 13:51/90分(変更なし)/incoming 車12分");
  console.log("⑥香川県立ミュージアム 15:36/70分(変更なし)/incoming 車15分(変更なし)、終わり16:46(16:30〜17:00の中)");

  if (!commit) {
    console.log("\n前提の確認OK。--commitで書き込みます。");
    return;
  }

  await prisma.$transaction(async (tx) => {
    await tx.itinerary.update({ where: { id: ITIN_ID }, data: { description: DESC_NEW } });
    await setDaySpotOrder(
      DAY_ID,
      [
        { id: IDS.castle, data: { memo: CASTLE_MEMO_NEW, visitTime: t(8, 30) } },
        {
          id: IDS.shoutengai,
          data: {
            memo: SHOUTENGAI_MEMO_NEW,
            visitTime: t(9, 45),
            stayDurationMin: 45,
          },
        },
        {
          id: IDS.yashima,
          data: {
            memo: YASHIMA_MEMO_NEW,
            visitTime: t(11, 23),
            transitLegs: {
              deleteMany: {},
              create: [
                { orderNo: 1, transitMode: "walk", transitDurationMin: 15 },
                { orderNo: 2, transitMode: "other", transitDurationMin: 15 },
                { orderNo: 3, transitMode: "car", transitDurationMin: 23 },
              ],
            },
          },
        },
        {
          create: {
            name: "屋島山上",
            lat: 34.358225,
            lng: 134.1022828,
            memo: LUNCH_MEMO,
            visitTime: t(12, 59),
            stayDurationMin: 40,
            transitLegs: { create: [{ orderNo: 1, transitMode: "walk", transitDurationMin: 6 }] },
          },
        },
        {
          id: IDS.shikokumura,
          data: {
            memo: SHIKOKUMURA_MEMO_NEW,
            visitTime: t(13, 51),
            transitLegs: { deleteMany: {}, create: [{ orderNo: 1, transitMode: "car", transitDurationMin: 12 }] },
          },
        },
        {
          id: IDS.museum,
          data: {
            memo: MUSEUM_MEMO_NEW,
            visitTime: t(15, 36),
          },
        },
      ],
      { tx }
    );
  });
  console.log("書き込みました。");
}
main().finally(() => prisma.$disconnect());
