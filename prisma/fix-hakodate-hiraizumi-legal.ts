async function main() {
  console.log("=== 確認 ===");
  for (const f of FIXES) {
    const spot = await prisma.spot.findUnique({
      where: { id: f.id },
      include: { day: { include: { itinerary: { select: { id: true, status: true } } } } },
    });
    if (!spot) throw new Error(`スポットが見つかりません: ${f.label} (${f.id})`);
    if (spot.day.itinerary.id !== f.itId) throw new Error(`対象外のしおりです: ${f.label}`);
    if (spot.day.itinerary.status !== "published") throw new Error(`公開中ではありません: ${f.label}`);
    if ((spot.memo ?? "") !== f.oldMemo) {
      throw new Error(`本文が想定と違います: ${f.label}\n実際: ${spot.memo}`);
    }
    console.log(`[OK] ${f.label} (${f.id})`);
    console.log(`  旧: ${f.oldMemo}`);
    console.log(`  新: ${f.newMemo}`);
  }

  if (!COMMIT) return console.log("\n確認モードです。--commit で書き込みます。");

  console.log("\n=== 書き込み ===");
  for (const f of FIXES) {
    await prisma.spot.update({ where: { id: f.id }, data: { memo: f.newMemo } });
    console.log(`  ${f.label}: COMMITTED`);
  }
}
main().finally(() => prisma.$disconnect());
