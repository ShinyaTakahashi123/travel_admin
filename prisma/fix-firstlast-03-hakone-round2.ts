  if (owaku.lat?.toString() !== "35.241861" || owaku.lng?.toString() !== "139.020806") {
    throw new Error(`大涌谷: 座標現在値が期待と不一致。現在値=${owaku.lat},${owaku.lng}`);
  }
  if (narukawa.lat?.toString() !== "35.200061" || narukawa.lng?.toString() !== "139.031195") {
    throw new Error(`成川美術館: 座標現在値が期待と不一致。現在値=${narukawa.lat},${narukawa.lng}`);
  }
  console.log("前提の確認OK。\n");

  console.log("[彫刻の森美術館] memo末尾: 「過ごしてください。」→「過ごしましょう。」");
  console.log("[箱根強羅公園] memo: 「日本国内でもっとも歴史あるフランス式整型庭園です。」→「日本でもっとも古いフランス式整型庭園とされています。」");
