/**
 * #163の続き。自己点検で、兼六園の書き出しの文が、別のしおり「兼六園の
 * 雪吊りと冬の金沢…」(41a20426)の書き出しとほぼ同じ(「金沢駅からバスで
 * およそ15分、水戸の偕楽園、岡山の後楽園とあわせて日本三名園の一つと
 * される、加賀藩前田家ゆかりの大名庭園・兼六園に[到着です/着きます]。」)
 * だったことに気づき、報告前に書き出しを変更した。あちらは冬の雪吊りが
 * 主題のため後続の文はまったく違うが、最初の一文だけほぼ同一だったため、
 * 「日本三名園」の位置を文の中ほどに移し、書き出しは「前田家の歴代藩主が
 * 長い年月をかけてつくり上げてきた」から始める構成に変更した。
 *
 * 実行方法: npm run prod -- npx tsx prisma/fix-163c-4bb849f5.ts
 */
import { prisma } from "../src/lib/prisma";

const DAY1_ID = "515a906f-e44c-48e7-9563-9a2aaf9deaee";

async function main() {
  const kenrokuen = await prisma.spot.findFirstOrThrow({ where: { dayId: DAY1_ID, name: "兼六園" } });

  if (!kenrokuen.memo?.startsWith("金沢駅からバスでおよそ15分、水戸の偕楽園")) {
    console.log("already applied, skipping");
    return;
  }

  await prisma.spot.update({
    where: { id: kenrokuen.id },
    data: {
      memo: "金沢駅からバスでおよそ15分、加賀藩前田家の歴代藩主が、長い年月をかけてつくり上げてきた大名庭園・兼六園に到着です。延宝4年(1676)、5代藩主・前田綱紀が、金沢城に面した傾斜地に別荘を建てたのが始まりとされ、歴代の藩主が手を加えながら、文久3年(1863)ごろに現在の姿になったと伝えられています。水戸の偕楽園、岡山の後楽園とあわせて日本三名園の一つとされ、「兼六園」という名前は、中国の書物にある、広大・幽邃(ゆうすい)・人力・蒼古・水泉・眺望という、相反するはずの6つの景観要素を兼ね備えているという意味に由来するのだそうです。池泉回遊式庭園ならではの、四季折々に移ろう景色をゆっくりと楽しみましょう。見学を終えたら、歩いて金沢神社へ向かいましょう。",
    },
  });

  console.log("#163続き: 兼六園の書き出しを、別のしおり(41a20426)と重ならない構成に変更");
  console.log("done");
}
main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
