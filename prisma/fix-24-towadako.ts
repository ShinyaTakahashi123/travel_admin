async function main() {
  const ids = [JINJA, OTOME, YUURANSEN, PURATTO, VISITOR_CENTER, ONABUYAMA, SHIMEITEI, HOKKETOGE, OYU];
  const spots = await prisma.spot.findMany({ where: { id: { in: ids } } });
  const byId = new Map(spots.map((s) => [s.id, s]));

  const checkTime = (id: string, h: number, m: number, label: string) => {
    const v = byId.get(id)!.visitTime;
    if (!v || v.getUTCHours() !== h || v.getUTCMinutes() !== m) throw new Error(`${label}: visitTimeの現在値が期待と不一致`);
  };
  checkTime(JINJA, 9, 0, "十和田神社");
  checkTime(OTOME, 9, 44, "乙女の像");
  checkTime(YUURANSEN, 10, 15, "十和田湖遊覧船");
  checkTime(ONABUYAMA, 13, 27, "御鼻部山展望台");
  checkTime(HOKKETOGE, 14, 41, "発荷峠展望台");
  checkTime(OYU, 15, 41, "大湯環状列石");
  if (byId.get(JINJA)!.memo !== JINJA_MEMO_OLD) throw new Error("十和田神社: memo現在値が期待と不一致");
  if (byId.get(YUURANSEN)!.memo !== YUURANSEN_MEMO_OLD) throw new Error("十和田湖遊覧船: memo現在値が期待と不一致");
  if (byId.get(ONABUYAMA)!.memo !== ONABUYAMA_MEMO_OLD) throw new Error("御鼻部山展望台: memo現在値が期待と不一致");
  if (byId.get(HOKKETOGE)!.memo !== HOKKETOGE_MEMO_OLD) throw new Error("発荷峠展望台: memo現在値が期待と不一致");
  if (byId.get(OYU)!.memo !== OYU_MEMO_OLD) throw new Error("大湯環状列石: memo現在値が期待と不一致");
  const it = await prisma.itinerary.findUniqueOrThrow({ where: { id: ITINERARY } });
  if (it.description !== DESC_OLD) throw new Error("説明文: 現在値が期待と不一致");

  console.log("前提の確認OK。\n");
  console.log("[Day1] 休屋のあたり(新規)12:20(35,昼食)→十和田神社13:06(20,walk11)→乙女の像13:30(15,walk4)→十和田湖遊覧船13:56(50,walk11)→御鼻部山展望台15:06(20,taxi20)→発荷峠展望台15:50(15,taxi24)→大湯環状列石16:35(23,taxi30、16:58出発)");
  console.log("[外した3か所] ぷらっと・十和田ビジターセンター・紫明亭展望台");
  console.log("[文] 休屋のあたり(新規、少ない便のバスの例外・昼食)。十和田神社・御鼻部山展望台・発荷峠展望台の書き出しを更新。遊覧船にタクシー予約の一文を追加。大湯環状列石のお墓の一文を直す。説明文から紫明亭を削除");
  console.log("[Day2] 時刻は変更なし(すでに範囲内)。移動手段はタクシー・徒歩・バスで、レンタカーは使っていないことを確認済み");

  if (!commit) {
    console.log("\n確認モードです。--commit を付けると書き込みます。");
    return;
  }

  await prisma.$transaction(async (tx) => {
    await tx.itinerary.update({ where: { id: ITINERARY }, data: { description: DESC_NEW } });

    await setDaySpotOrder(
      DAY1,
      [
        {
          create: {
            name: "休屋のあたり",
            memo: YASUMIYA_MEMO,
            lat: 40.4264975,
            lng: 140.8945001,
            visitTime: t(12, 20),
            stayDurationMin: 35,
          },
        },
        {
          id: JINJA,
          data: {
            visitTime: t(13, 6),
            stayDurationMin: 20,
            memo: JINJA_MEMO_NEW,
            transitLegs: { deleteMany: {}, create: [{ orderNo: 1, transitMode: "walk", transitDurationMin: 11 }] },
          },
        },
        { id: OTOME, data: { visitTime: t(13, 30), stayDurationMin: 15 } },
        {
          id: YUURANSEN,
          data: { visitTime: t(13, 56), memo: YUURANSEN_MEMO_NEW },
        },
        {
          id: ONABUYAMA,
          data: {
            visitTime: t(15, 6),
            stayDurationMin: 20,
            memo: ONABUYAMA_MEMO_NEW,
            transitLegs: { deleteMany: {}, create: [{ orderNo: 1, transitMode: "car", transitDurationMin: 20 }] },
          },
        },
        {
          id: HOKKETOGE,
          data: {
            visitTime: t(15, 50),
            stayDurationMin: 15,
            memo: HOKKETOGE_MEMO_NEW,
            transitLegs: { deleteMany: {}, create: [{ orderNo: 1, transitMode: "car", transitDurationMin: 24 }] },
          },
        },
        { id: OYU, data: { visitTime: t(16, 35), stayDurationMin: 23, memo: OYU_MEMO_NEW } },
      ],
      { remove: [PURATTO, VISITOR_CENTER, SHIMEITEI], tx }
    );
  });
  console.log("\n書き込みました。");
}

main().finally(() => prisma.$disconnect());
