  console.log("\n[大通公園] 座標 43.059722,141.346389 → 43.0599018,141.3475101（OSM way 64733385）");
  console.log("[北海道庁旧本庁舎] 座標 43.064438,141.347061 → 43.0639656,141.3480242（OSM way 36331476）");
